CREATE TABLE IF NOT EXISTS categories
(
    category_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_title     VARCHAR(255),
    image_url          VARCHAR(255),
    parent_category_id INTEGER,
    created_at         TIMESTAMP WITH TIME ZONE,
    updated_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_category_id) REFERENCES categories (category_id)
);

CREATE INDEX IF NOT EXISTS idx_categories_parent_id ON categories (parent_category_id);

CREATE TABLE IF NOT EXISTS products
(
    product_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_title VARCHAR(255),
    image_url     VARCHAR(255),
    sku           VARCHAR(255) UNIQUE,
    price_unit    DOUBLE PRECISION,
    quantity      INTEGER,
    category_id   INTEGER,
    created_at    TIMESTAMP WITH TIME ZONE,
    updated_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (category_id)
);

CREATE INDEX IF NOT EXISTS idx_products_category_id ON products (category_id);
