CREATE TABLE IF NOT EXISTS carts
(
    cart_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_carts_user_id ON carts (user_id);

CREATE TABLE IF NOT EXISTS orders
(
    order_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date TIMESTAMP,
    order_desc VARCHAR(255),
    order_fee  DOUBLE PRECISION,
    product_id INTEGER,
    cart_id    INTEGER,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_orders_cart FOREIGN KEY (cart_id) REFERENCES carts (cart_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_orders_cart_id ON orders (cart_id);
CREATE INDEX IF NOT EXISTS idx_orders_product_id ON orders (product_id);
